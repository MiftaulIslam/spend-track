/**
 * SpendTrack — database schema (Drizzle).
 *
 * Conventions
 * -----------
 *  * Money is ALWAYS an integer number of minor units (cents) held as `bigint`,
 *    paired with an ISO-4217 currency code. No float, no Decimal, anywhere a
 *    balance can be derived from. `mode: "bigint"` is what enforces that at the
 *    driver boundary — the default (`mode: "number"`) hands back a float.
 *  * Rates are `numeric(24, 12)` and surface as strings. That is deliberate:
 *    `src/domain/fx.ts` parses them into scaled integers and does the
 *    arithmetic itself, so no float ever touches a conversion.
 *  * Timestamps and dates are `mode: "date"`, so the domain keeps working in
 *    `Date` the way the schedule and period maths expects.
 *  * Every user-owned table carries `userId` and indexes it first in the
 *    composite indexes, because every query is already scoped to one user.
 *  * Soft delete is `deletedAt`; archival (a user-visible, permanent state) is
 *    `archivedAt`. They are different things and both exist on purpose.
 *
 * Generated by introspecting the live database, then corrected for the three
 * things introspection cannot know (see scripts note in docs/database.md).
 */

